import { chromium, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const token = process.env.NEURAXIS_QA_TOKEN;
if (!token) throw new Error('Set NEURAXIS_QA_TOKEN to the disposable local test-session token');
const base = process.env.NEURAXIS_QA_URL ?? 'http://127.0.0.1:4180';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Native browser gate requires loopback');
const out = process.env.NEURAXIS_QA_OUTPUT ?? join(tmpdir(), 'neuraxis-native-qa');
mkdirSync(out, {recursive:true});
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1600,height:900}});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
try {
  await page.addInitScript(()=>localStorage.setItem('caos.lang','en'));
  await page.goto(`${base}/?mode=investigations&suite=core&incident=C01&controller=M01&compare=M12&condition=nominal&seed=40000#local-session=${encodeURIComponent(token)}`);
  const fresh=page.getByRole('region',{name:'Fresh local investigation',exact:true});
  await expect(fresh.getByRole('button',{name:'Run selected controller',exact:true})).toBeEnabled();
  const start=page.waitForResponse(r=>r.url().endsWith('/api/run')&&r.request().method()==='POST');
  await fresh.getByRole('button',{name:'Run selected controller',exact:true}).click();
  const first=await(await start).json();
  await expect(fresh).toContainText('Independent goal check: passed',{timeout:30000});
  const response=await page.request.get(`${base}/api/events?run_id=${first.run_id}`,{headers:{Authorization:`Bearer ${token}`}});
  const record=await response.json();
  expect(record.episode.metrics.native_receipts).toBeGreaterThan(0);
  expect(record.episode.provenance.execution_origin).toBe('fresh-local');
  expect(record.episode.provenance.suite).toBe('core');
  expect(new URL(page.url()).hash).toBe('');
  const download=page.waitForEvent('download');
  await fresh.getByRole('button',{name:'Export fresh evidence',exact:true}).click();
  await (await download).saveAs(join(out,'fresh-core.json'));
  await page.getByRole('combobox',{name:'Software incident',exact:true}).selectOption('C07');
  const secondResponse=page.waitForResponse(r=>r.url().endsWith('/api/run')&&r.request().method()==='POST');
  await fresh.getByRole('button',{name:'Run selected controller',exact:true}).click();
  const second=await(await secondResponse).json();
  await fresh.getByRole('button',{name:'Cancel fresh run',exact:true}).click();
  await expect(fresh.getByRole('button',{name:'Cancel fresh run',exact:true})).toHaveCount(0,{timeout:30000});
  const cancelled=await (await page.request.get(`${base}/api/events?run_id=${second.run_id}`,{headers:{Authorization:`Bearer ${token}`}})).json();
  expect(['cancelled','succeeded','failed']).toContain(cancelled.status);
  const badAuth=await page.request.post(`${base}/api/run`,{data:{case_id:'C01',method_id:'M01'}});
  expect(badAuth.status()).toBe(401);
  expect(errors).toEqual([]);
  await page.screenshot({path:join(out,'native-result.png')});
  const report={coreStatus:record.status,nativeReceipts:record.episode.metrics.native_receipts,freshProvenance:true,fragmentRemoved:true,cancellationStatus:cancelled.status,unauthenticatedStatus:badAuth.status(),errors};
  writeFileSync(join(out,'native-report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
