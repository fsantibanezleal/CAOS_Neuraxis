// Generates src/lib/contract.gen.ts from ../docs/contracts/api.openapi.json and the schema files of
// ../docs/contracts/schemas/ (ADR-0080 decision 2: the schema files are the single source of every contract; the
// TypeScript types are generated, never hand-written). `--check` generates in memory and fails when the committed
// file differs, so a schema change without a regeneration stops `npm run build` (the currency check; no CI job of
// its own, ADR-0074).
//
// The OpenAPI document of the operations API references only the operation-run schema file. The other document
// schemas (episode, lineage, the evidence documents, readiness, ...) are added here to the generator's INPUT as
// components named by DOCUMENTS below; the OpenAPI document itself is not edited. A schema file that is not in
// DOCUMENTS and not referenced by the document fails the generation, so a new schema cannot be left without a type.
// Each file keeps its shared definitions in `$defs`, as a self-contained JSON Schema must; openapi-typescript would
// render `$defs` as a property of every document type, so the files are inlined first: every `$defs` entry becomes a
// component and its `#/$defs/<name>` references point at it. A name defined twice must be defined identically
// (one type per name), or the generation fails.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, '..', '..', 'docs', 'contracts');
const target = join(here, '..', 'src', 'lib', 'contract.gen.ts');
const HEADER =
  '// GENERATED by frontend/scripts/gen-contract-types.mjs from docs/contracts/api.openapi.json and docs/contracts/schemas/. Do not edit.\n';

/** The component name each document schema file generates (the file name without `.schema.json`). */
export const DOCUMENTS = {
  'benchmark-adequacy': 'BenchmarkAdequacy',
  'episode-index': 'EpisodeIndex',
  episode: 'EpisodeDocument',
  lineage: 'Lineage',
  'operation-index': 'OperationIndex',
  'operation-run': 'OperationRunDocument',
  readiness: 'Readiness',
  'release-manifest': 'ReleaseManifest',
  'research-summary': 'ResearchSummary',
  'routing-study': 'RoutingStudy',
  'semantic-transfer-index': 'SemanticTransferIndex',
  'semantic-transfer-report': 'SemanticTransferReport',
};

const readJSON = (path) => JSON.parse(readFileSync(path, 'utf8'));
const schemaFile = (name) => join(contracts, 'schemas', `${name}.schema.json`);

/** The JSON pointer `#/a/b` resolved inside `root`. */
function pointer(root, ptr, from) {
  let node = root;
  for (const part of ptr.split('/').slice(1)) {
    node = node?.[part.replace(/~1/g, '/').replace(/~0/g, '~')];
    if (node === undefined) throw new Error(`${from}: unresolved pointer #${ptr}`);
  }
  return node;
}

/**
 * A copy of `node` where every reference is a local one: `#/$defs/<name>` becomes the component `<name>`, a
 * reference to a schema file becomes the component of that document, and a reference into a file
 * (`file#/properties/events/items`) is replaced by the fragment it names, relinked.
 */
function relink(node, baseDir, from) {
  if (Array.isArray(node)) return node.map((n) => relink(n, baseDir, from));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key !== '$ref' || typeof value !== 'string') {
      out[key] = relink(value, baseDir, from);
      continue;
    }
    if (value.startsWith('#/$defs/')) out[key] = `#/components/schemas/${value.slice('#/$defs/'.length)}`;
    else if (value.startsWith('#/components/')) out[key] = value;
    else {
      const [file, frag] = value.split('#');
      const name = posix.basename(file).replace(/\.schema\.json$/, '');
      if (!(name in DOCUMENTS)) throw new Error(`${from}: ${value} references a schema file with no component`);
      if (frag) {
        const fragment = pointer(readJSON(schemaFile(name)), frag, from);
        Object.assign(out, relink(fragment, dirname(schemaFile(name)), `${from} -> ${value}`));
      } else out[key] = `#/components/schemas/${DOCUMENTS[name]}`;
    }
  }
  return out;
}

/** The OpenAPI document with every document schema added as a component and every `$defs` hoisted. */
export function inlineDocument() {
  const doc = readJSON(join(contracts, 'api.openapi.json'));
  const schemas = doc.components.schemas;
  const files = readdirSync(join(contracts, 'schemas'))
    .filter((f) => f.endsWith('.schema.json'))
    .map((f) => f.replace(/\.schema\.json$/, ''));
  for (const name of files) if (!(name in DOCUMENTS)) throw new Error(`schema ${name} has no entry in DOCUMENTS`);
  for (const name of Object.keys(DOCUMENTS)) if (!files.includes(name)) throw new Error(`DOCUMENTS names ${name}, which has no schema file`);
  const hoisted = {};
  for (const [name, component] of Object.entries(DOCUMENTS)) {
    if (component in schemas) throw new Error(`component ${component} of ${name} collides with an OpenAPI component`);
    const { $defs = {}, $schema: _dialect, $id: _id, ...body } = readJSON(schemaFile(name));
    for (const [defName, def] of Object.entries($defs)) {
      const linked = relink(def, join(contracts, 'schemas'), `${name}#/$defs/${defName}`);
      if (defName in schemas || Object.values(DOCUMENTS).includes(defName)) throw new Error(`$defs ${defName} of ${name} collides with a component`);
      if (defName in hoisted && JSON.stringify(hoisted[defName]) !== JSON.stringify(linked)) {
        throw new Error(`$defs ${defName} differs between schema files: one name, one definition`);
      }
      hoisted[defName] = linked;
    }
    schemas[component] = relink(body, join(contracts, 'schemas'), name);
  }
  for (const [name, schema] of Object.entries(schemas)) {
    if (name in hoisted || Object.values(DOCUMENTS).includes(name)) continue;
    schemas[name] = relink(schema, contracts, `api.openapi.json#/components/schemas/${name}`);
  }
  for (const [path, item] of Object.entries(doc.paths ?? {})) doc.paths[path] = relink(item, contracts, `api.openapi.json ${path}`);
  Object.assign(schemas, hoisted);
  return doc;
}

const ast = await openapiTS(inlineDocument());
const body = astToString(ast).replace(/\r\n/g, '\n').replace(/\s+$/, '');
const text = `${HEADER}${body}\n`;

if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = readFileSync(target);
  } catch {
    // an absent file is not current
  }
  if (current === null || !current.equals(Buffer.from(text, 'utf8'))) {
    console.error('contract.gen.ts is not current: run npm run contracts:types');
    process.exit(1);
  }
  console.log('contract types: current');
} else {
  writeFileSync(target, text, 'utf8');
  console.log('contract types: wrote frontend/src/lib/contract.gen.ts');
}
